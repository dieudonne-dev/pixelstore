-- Profil utilisateur relié à auth.users (Supabase Auth)
CREATE TABLE IF NOT EXISTS public.users (
  id         uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  first_name text,
  last_name  text,
  email      text UNIQUE,
  phone      text,
