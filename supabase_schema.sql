  updated_at timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE public.users IS 'Profil utilisateur synchronisé avec Supabase Auth';

-- Trigger : profil auto-créé à l'inscription
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  -- L'email administrateur fixe devient automatiquement admin.
  INSERT INTO public.users (id, email, first_name, last_name, role)
  SELECT NEW.id, NEW.email,
         coalesce(NULLIF(NEW.raw_user_meta_data->>'first_name',''),
                  NULLIF(split_part(coalesce(NEW.raw_user_meta_data->>'full_name',''), ' ', 1), ''),
                  ''),
         coalesce(NULLIF(NEW.raw_user_meta_data->>'last_name',''),
                  CASE WHEN position(' ' in coalesce(NEW.raw_user_meta_data->>'full_name','')) > 0
                       THEN substr(coalesce(NEW.raw_user_meta_data->>'full_name',''),
                                   position(' ' in coalesce(NEW.raw_user_meta_data->>'full_name','')) + 1)
                       ELSE '' END,
                  ''),
         CASE WHEN lower(NEW.email) = lower('admin@pixelstore.bi') THEN 'admin'::text ELSE 'user'::text END;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

CREATE OR REPLACE FUNCTION public.handle_user_update()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  UPDATE public.users
     SET email = NEW.email,
         role = CASE WHEN lower(NEW.email) = lower('admin@pixelstore.bi')
                     THEN 'admin'::text ELSE role END,
         updated_at = now()
   WHERE id = NEW.id;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_updated ON auth.users;
CREATE TRIGGER on_auth_user_updated
  AFTER UPDATE OF email ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_user_update();

-- Helper : l'utilisateur courant est-il admin ?
-- (défini ici, après la création de public.users qu'il référence)
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.users
    WHERE id = auth.uid() AND role = 'admin'
  );
$$;

