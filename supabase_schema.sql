-- Produits disponibles (stock réel > 0), avec image principale, tag, prix
CREATE OR REPLACE VIEW public.v_products_available AS
SELECT p.id, p.name, p.slug, p.reference, p.tag, p.price, p.old_price,
       p.rating, p.warranty, c.name AS category, b.name AS brand,
       (s.quantity - s.reserved_quantity) AS available_qty,
       pi.image_url AS main_image
FROM public.products p
LEFT JOIN public.categories c ON c.id = p.category_id
LEFT JOIN public.brands b ON b.id = p.brand_id
LEFT JOIN public.stock s ON s.product_id = p.id
LEFT JOIN LATERAL (
  SELECT image_url FROM public.product_images
  WHERE product_id = p.id ORDER BY sort_order LIMIT 1
) pi ON true
WHERE p.is_active AND (s.quantity - s.reserved_quantity) > 0;

-- Alerte stock faible / rupture
CREATE OR REPLACE VIEW public.v_low_stock AS
SELECT p.id, p.name, p.reference, s.quantity, s.reserved_quantity,
       (s.quantity - s.reserved_quantity) AS available,
       s.low_stock_threshold
FROM public.products p
JOIN public.stock s ON s.product_id = p.id
WHERE (s.quantity - s.reserved_quantity) <= s.low_stock_threshold;

-- Résumé des commandes par statut
CREATE OR REPLACE VIEW public.v_order_summary AS
SELECT status, COUNT(*) AS order_count, COALESCE(SUM(grand_total),0) AS total_amount
FROM public.orders
GROUP BY status;

-- Chiffre d'affaires total
CREATE OR REPLACE VIEW public.v_revenue AS
SELECT COALESCE(SUM(grand_total),0) AS total_revenue,
       COUNT(*) AS total_orders
FROM public.orders
WHERE status NOT IN ('cancelled','refunded');

-- Fiche produit complète (galerie, specs, certificat) pour produit.html
CREATE OR REPLACE VIEW public.v_product_full AS
SELECT p.*,
       c.name AS category, b.name AS brand,
       COALESCE(
         (SELECT jsonb_agg(jsonb_build_object('label',s.label,'value',s.value) ORDER BY s.sort_order)
          FROM public.product_specs s WHERE s.product_id = p.id), '[]'::jsonb) AS specs,
       COALESCE(
         (SELECT jsonb_agg(image_url ORDER BY sort_order)
          FROM public.product_images WHERE product_id = p.id), '[]'::jsonb) AS gallery,
       (SELECT jsonb_build_object('title', title, 'number', number, 'authority', authority,
                                 'cert_date', cert_date, 'points', points)
        FROM public.product_certificates c2 WHERE c2.product_id = p.id) AS cert,
       (SELECT quantity FROM public.stock WHERE product_id = p.id) AS stock
FROM public.products p
LEFT JOIN public.categories c ON c.id = p.category_id
LEFT JOIN public.brands b ON b.id = p.brand_id;

-- ============================================================
-- FONCTION : créer une commande (décrémente le stock)
-- ============================================================
CREATE OR REPLACE FUNCTION public.create_order(
  p_payment_method text,
  p_coupon_code text DEFAULT NULL,
  p_shipping_address_id uuid DEFAULT NULL,
  p_billing_address_id uuid DEFAULT NULL,
  p_notes text DEFAULT NULL
)
RETURNS TABLE(order_id uuid, order_number text, subtotal numeric, discount_total numeric, grand_total numeric)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_cart_id        uuid;
  v_order_id       uuid;
  v_subtotal       numeric(12,2) := 0;
  v_discount       numeric(12,2) := 0;
  v_coupon_id      bigint;
  v_item           record;
  v_avail          integer;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Utilisateur non authentifié';
  END IF;

  SELECT id INTO v_cart_id FROM public.carts WHERE user_id = auth.uid();
  IF v_cart_id IS NULL THEN
    RAISE EXCEPTION 'Panier vide ou introuvable';
  END IF;

  IF p_coupon_code IS NOT NULL THEN
    SELECT ci.id, ci.discount_value
      INTO v_coupon_id, v_discount
    FROM public.coupons ci
    WHERE ci.code = p_coupon_code AND ci.is_active
      AND (ci.expires_at IS NULL OR ci.expires_at > now())
    LIMIT 1;
  END IF;

  INSERT INTO public.orders (order_number, user_id, coupon_id, payment_method,
                             shipping_address_id, billing_address_id, customer_notes)
  VALUES ('PS-' || to_char(now(),'YYYYMMDD') || '-' ||
          lpad((floor(random()*99999))::text, 5, '0'),
          auth.uid(), v_coupon_id, p_payment_method,
          p_shipping_address_id, p_billing_address_id, p_notes)
  RETURNING id INTO v_order_id;

  FOR v_item IN
    SELECT ci.product_id, ci.quantity, p.price
    FROM public.cart_items ci
    JOIN public.products p ON p.id = ci.product_id
    WHERE ci.cart_id = v_cart_id
  LOOP
    SELECT (quantity - reserved_quantity) INTO v_avail
    FROM public.stock WHERE product_id = v_item.product_id;

    IF v_avail IS NULL OR v_avail < v_item.quantity THEN
      RAISE EXCEPTION 'Stock insuffisant pour le produit %', v_item.product_id;
    END IF;

    INSERT INTO public.order_items (order_id, product_id, product_name, quantity,
                                    unit_price, subtotal)
    SELECT v_order_id, p.id, p.name, v_item.quantity, p.price, p.price * v_item.quantity
    FROM public.products p WHERE p.id = v_item.product_id;

    UPDATE public.stock SET quantity = quantity - v_item.quantity
    WHERE product_id = v_item.product_id;

    INSERT INTO public.stock_movements (product_id, user_id, quantity, movement_type, reference)
    VALUES (v_item.product_id, auth.uid(), -v_item.quantity, 'sale', v_order_id::text);

    v_subtotal := v_subtotal + (v_item.price * v_item.quantity);
  END LOOP;

  IF v_coupon_id IS NOT NULL AND v_discount > v_subtotal THEN
    v_discount := v_subtotal;
  END IF;

  UPDATE public.orders
  SET subtotal = v_subtotal,
      discount_total = v_discount,
      shipping_cost = 5000,
      grand_total = v_subtotal - v_discount + 5000
  WHERE id = v_order_id;

  INSERT INTO public.order_status_history (order_id, status, changed_by, note)
  VALUES (v_order_id, 'pending', auth.uid(), 'Commande créée');

  IF v_coupon_id IS NOT NULL THEN
    UPDATE public.coupons SET times_used = times_used + 1 WHERE id = v_coupon_id;
  END IF;

  DELETE FROM public.cart_items WHERE cart_id = v_cart_id;

  RETURN QUERY SELECT v_order_id,
    (SELECT o.order_number FROM public.orders o WHERE o.id = v_order_id),
    v_subtotal, v_discount, v_subtotal - v_discount + 5000;
END;
$$;

